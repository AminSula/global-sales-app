-- Step 3: offers, and "one agent per customer per day".

-- A customer can be assigned to only ONE agent on a given day.
-- (This replaces the old rule, which only stopped the same agent getting a customer twice.)
ALTER TABLE visit_assignment DROP CONSTRAINT uq_visit_agent_customer_day;
ALTER TABLE visit_assignment ADD CONSTRAINT uq_visit_customer_day UNIQUE (customer_id, visit_date);

-- The simple per-product discount is now an offer (one product, all customers).
ALTER TABLE product DROP COLUMN discount_percent;

-- An offer: a percentage off one or more products, for all customers or for chosen ones.
-- start_date / end_date are optional (both inclusive); enabled = FALSE pauses the offer.
CREATE TABLE offer (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name              VARCHAR(100)  NOT NULL,
    discount_percent  NUMERIC(5, 2) NOT NULL CHECK (discount_percent > 0 AND discount_percent <= 100),
    all_customers     BOOLEAN       NOT NULL DEFAULT TRUE,
    start_date        DATE,
    end_date          DATE,
    enabled           BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at        TIMESTAMP     NOT NULL
);

CREATE TABLE offer_product (
    offer_id    BIGINT NOT NULL REFERENCES offer (id),
    product_id  BIGINT NOT NULL REFERENCES product (id),
    PRIMARY KEY (offer_id, product_id)
);

-- Only used when offer.all_customers = FALSE.
CREATE TABLE offer_customer (
    offer_id     BIGINT NOT NULL REFERENCES offer (id),
    customer_id  BIGINT NOT NULL REFERENCES customer (id),
    PRIMARY KEY (offer_id, customer_id)
);

-- The order line keeps the NAME of the offer that gave its discount (empty when there was none),
-- so reports still work after an offer is edited or deleted.
ALTER TABLE sales_order_line ADD COLUMN offer_name VARCHAR(100);
