--  SHËNIM: aplikacioni i krijon vetë këto tabela herën e parë që niset (me skriptet në
--  backend/src/main/resources/db/migration). Ky skedar është i njëjti rezultat i mbledhur në
--  një vend, për shqyrtim ose për t'u ekzekutuar me dorë nga administratori i bazës së të
--  dhënave. Mos i përdorni të dyja mënyrat në të njëjtën bazë.
--
--  Për një motor tjetër (p.sh. Microsoft SQL Server) duhen vetëm ndryshime të vogla:
--    BOOLEAN                              -> BIT
--    GENERATED BY DEFAULT AS IDENTITY     -> IDENTITY(1,1)
--    TRUE / FALSE                         -> 1 / 0
-- =====================================================================================


-- Llogaritë: 1 administrator dhe agjentët e shitjes.
-- Fjalëkalimi ruhet vetëm si hash (BCrypt), asnjëherë si tekst.
CREATE TABLE app_user (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username       VARCHAR(50)  NOT NULL UNIQUE,
    password_hash  VARCHAR(100) NOT NULL,
    full_name      VARCHAR(100) NOT NULL,
    role           VARCHAR(10)  NOT NULL CHECK (role IN ('ADMIN', 'AGENT')),
    active         BOOLEAN      NOT NULL DEFAULT TRUE
);

-- Kopja jonë e produkteve të lexuara nga SQL (përditësohet me butonin "Rifresko").
CREATE TABLE product (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code       VARCHAR(30)    NOT NULL UNIQUE,
    name       VARCHAR(150)   NOT NULL,
    price      NUMERIC(12, 2) NOT NULL,
    stock      NUMERIC(12, 2) NOT NULL,
    active     BOOLEAN        NOT NULL DEFAULT TRUE,   -- FALSE: produkti nuk ekziston më në burim
    synced_at  TIMESTAMP      NOT NULL                 -- kur u lexua për herë të fundit
);

-- Kopja jonë e klientëve të lexuar nga SQL.
CREATE TABLE customer (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code       VARCHAR(30)  NOT NULL UNIQUE,
    name       VARCHAR(150) NOT NULL,
    address    VARCHAR(250),
    active     BOOLEAN      NOT NULL DEFAULT TRUE,
    synced_at  TIMESTAMP    NOT NULL
);

-- Caktimet: cilët klientë viziton një agjent në një ditë dhe me çfarë rendi.
-- Një klient mund t'i caktohet vetëm NJË agjenti në të njëjtën ditë.
CREATE TABLE visit_assignment (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agent_id     BIGINT  NOT NULL REFERENCES app_user (id),
    customer_id  BIGINT  NOT NULL REFERENCES customer (id),
    visit_date   DATE    NOT NULL,
    visit_order  INTEGER NOT NULL,
    CONSTRAINT uq_visit_customer_day UNIQUE (customer_id, visit_date)
);

CREATE INDEX ix_visit_agent_day ON visit_assignment (agent_id, visit_date);

-- Ofertat: zbritje në përqindje për një ose më shumë produkte,
-- për të gjithë klientët ose vetëm për klientë të zgjedhur.
-- start_date / end_date janë opsionale (të dyja ditët përfshihen); enabled = FALSE e ndal ofertën.
CREATE TABLE offer (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name              VARCHAR(100)  NOT NULL,
    discount_percent  NUMERIC(5, 2) NOT NULL CHECK (discount_percent > 0 AND discount_percent <= 100),
    all_customers     BOOLEAN       NOT NULL DEFAULT TRUE,
    start_date        DATE,
    end_date          DATE,
    enabled           BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at        TIMESTAMP     NOT NULL
);

CREATE TABLE offer_product (
    offer_id    BIGINT NOT NULL REFERENCES offer (id),
    product_id  BIGINT NOT NULL REFERENCES product (id),
    PRIMARY KEY (offer_id, product_id)
);

-- Përdoret vetëm kur offer.all_customers = FALSE.
CREATE TABLE offer_customer (
    offer_id     BIGINT NOT NULL REFERENCES offer (id),
    customer_id  BIGINT NOT NULL REFERENCES customer (id),
    PRIMARY KEY (offer_id, customer_id)
);

-- POROSIA (koka).
-- client_request_id krijohet në telefon një herë për çdo porosi; kufizimi UNIQUE është ai që
-- pengon regjistrimin e së njëjtës porosi dy herë (shtypje e përsëritur ose ridërgim).
CREATE TABLE sales_order (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number       VARCHAR(20)    NOT NULL UNIQUE,                 -- numri i porosisë, p.sh. POR-000123
    client_request_id  VARCHAR(36)    NOT NULL UNIQUE,
    customer_id        BIGINT         NOT NULL REFERENCES customer (id),   -- klienti
    agent_id           BIGINT         NOT NULL REFERENCES app_user (id),   -- agjenti
    created_at         TIMESTAMP      NOT NULL,                        -- data
    total              NUMERIC(14, 2) NOT NULL,                        -- totali
    status             VARCHAR(10)    NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'APPROVED')),
    approved_at        TIMESTAMP,                                      -- kur u miratua
    approved_by        BIGINT REFERENCES app_user (id)                 -- kush e miratoi
);

CREATE INDEX ix_order_agent ON sales_order (agent_id, created_at);

-- RRESHTAT E POROSISË.
-- Kodi, emri, çmimi, zbritja dhe emri i ofertës KOPJOHEN këtu në çastin e regjistrimit,
-- prandaj ndryshimi i mëvonshëm i çmimit ose i ofertës nuk e ndryshon një porosi të regjistruar.
CREATE TABLE sales_order_line (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id          BIGINT         NOT NULL REFERENCES sales_order (id),
    line_no           INTEGER        NOT NULL,
    product_id        BIGINT         NOT NULL REFERENCES product (id),
    product_code      VARCHAR(30)    NOT NULL,
    product_name      VARCHAR(150)   NOT NULL,
    quantity          NUMERIC(12, 2) NOT NULL CHECK (quantity > 0),     -- sasia
    unit_price        NUMERIC(12, 2) NOT NULL,                          -- çmimi në çastin e porosisë
    discount_percent  NUMERIC(5, 2)  NOT NULL DEFAULT 0,                -- zbritja në %
    line_total        NUMERIC(14, 2) NOT NULL,                          -- sasia x çmimi x (100 - zbritja) / 100
    offer_name        VARCHAR(100),                                     -- oferta që dha zbritjen (bosh nëse s'ka)
    CONSTRAINT uq_order_line UNIQUE (order_id, line_no)
);
